def calc_geop_accel(r_earth: np.ndarray, n_max: int = N_MAX):
    f = np.zeros(3)
    r_xy = np.linalg.norm(r_earth[:2])
    r_abs = np.linalg.norm(r_earth)
    x = r_earth / r_abs
    
    if r_xy < eps:
        cosL = 1.0
        sinL = 0.0
    else:
        cosL = r_earth[0] / r_xy
        sinL = r_earth[1] / r_xy

    cosphi = r_xy / r_abs       # cos(phi)
    sinphi = x[2]               # sin(phi)
    
    R = Re / r_abs

    W1 = 0.0
    W2 = 0.0
    W3 = 0.0
    W4 = 0.0

    # Значения cos(ml), sin(ml), cos((m-1)l), sin((m-1)l) для начального
    # значения m = 1
    cosm1L = 1.0                # cos((m-1) * lambda )
    sinm1L = 0.0                # sin((m-1) * lambda)
    cosmL  = cosL               # cos(m * lambda)
    sinmL  = sinL               # sin(m * lambda)

    # Позиции в массиве коэффициентов CS(pos_nm) = C_nm, CS(pos_nm+1) = S_nm
    # за исключением S_n0 = 0, которые не входят в массив.
    pos_mm  = 1                 # Позиция первого элемента (m, m), m = 1
    pos_nm1 = 0                 # Позиция элемента (n, m-1)

    P_mm = 1.0                  # P_mm(x), при m = 0
    R_m  = R                    # (Re / r)^m, m = 1

    # Суммирование с m = 1, то есть без зональных гармоник
    for m in range(1, n_max + 1):
        # Внешний цикл по строкам. Начало с диагонального элемента (m, m)
        P_nm = P_mm             # Начинаем с n = m
        P_n1m = 0.0             # P_n-1,m(x) = 0, при n = m
        pos_nm = pos_mm         # Начинаем с n = m
        R_n = R_m               # Начинаем с n = m
        n1 = m + 1              # Значение n + 1, начинаем с n = m
        
        dW2 = 0.0
        dW3 = 0.0

        for n in range(m, n_max + 1):
            # Внутренний цикл
            P_nmR = P_nm * R_n  # Произведение P_nm(sin(phi)) * (R/r)^n

            # Частные суммы
            dW = P_nmR * (CS[pos_nm] * cosmL + CS[pos_nm+1] * sinmL)
            W1 += n1 * dW
            dW2 += dW
            dW3 += P_nmR * (-CS[pos_nm] * sinmL + CS[pos_nm + 1] * cosmL)
            W4 += P_nmR * (CS[pos_nm1] * cosm1L + CS[pos_nm1 + 1] * sinm1L)

            # Обновление n -> n + 1
            R_n = R_n * R
            P_n2m = P_n1m
            P_n1m = P_nm
            n21 = n + n1        # 2n + 1
            # Рекуррентное соотношение для P_n+1,m через P_nm и P_n-1,m
            P_nm = (n21 * sinphi * P_n1m - (n + m) * P_n2m) / (n1 - m)

            n1 += 1
            pos_nm1 = pos_nm1 + n21
            pos_nm = pos_nm + n21

        # Обновление частных сумм
        W2 += m * dW2
        W3 += m * dW3

        # Переход с следующей строке и диагональному элементоу m -> m + 1
        R_m = R_m * R           # (R / r)^m
        cosm1L = cosmL
        sinm1L = sinmL
        cosmL = cosm1L * cosL - sinm1L * sinL # cos((m+1) * lambda)
        sinmL = cosm1L * sinL + sinm1L * cosL # sin((m+1) * lambda)
        n21 = m + m + 1

        # Рекуррентное соотношение для 
        P_mm = n21 * cosphi * P_mm # P_mm -> P_m+1,m+1
        pos_nm1 = n21 + pos_mm
        pos_mm = pos_nm1 + 2


    # Учет вклада зональных гармоник
    P_n1m = 1.
    P_nm = sinphi
    pos_mm = 0                  # n = 0, m = 0
    R_n = R
    W1 = W1 * cosphi

    for n in range(1, n_max + 1):
        W1 += (n + 1) * CS[pos_mm] * R_n * P_nm
        if n == n_max:
            continue

        n1 = n + 1
        R_n = R_n * R
        P_n2m = P_n1m
        P_n1m = P_nm
        n21 = n + n1
        P_nm = (n21 * sinphi * P_n1m - n * P_n2m) / n1
        pos_mm = pos_mm + n21

    # Вычисление ускорения

    coeff = -muE / (r_abs * r_abs)
    W2 = W4 * cosphi - W2 * sinphi
    f[2] = (W1 * sinphi - W2 * cosphi) * coeff
    W2 = W2 * sinphi
    f[0] = (W2 * cosL + W3 * sinL + W1 * x[0]) * coeff
    f[1] = (W2 * sinL - W3 * cosL + W1 * x[1]) * coeff

    return f
    

